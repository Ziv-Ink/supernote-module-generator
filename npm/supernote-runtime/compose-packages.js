'use strict';

const fs = require('fs');
const path = require('path');

const {discover} = require('./resolve-packages.js');

function atomicWrite(destination, content) {
  fs.mkdirSync(path.dirname(destination), {recursive: true});
  const temporary = `${destination}.tmp-${process.pid}`;
  fs.writeFileSync(temporary, content, {encoding: 'utf8', mode: 0o644});
  try {
    fs.renameSync(temporary, destination);
  } catch (error) {
    if (!error || !['EEXIST', 'EPERM'].includes(error.code)) throw error;
    fs.rmSync(destination, {force: true});
    fs.renameSync(temporary, destination);
  }
}

function renderFeatureRegistry(modules) {
  const rows = modules.map(module =>
    `    {${JSON.stringify(module.featureId)}, ${JSON.stringify(module.publicName)}},`).join('\n');
  return `// Generated by @supernote/runtime. Do not edit.
#include <array>
#include <cstddef>

namespace supernote::generated {

struct FeatureDescriptor {
  const char *feature_id;
  const char *public_name;
};

namespace {
constexpr std::array<FeatureDescriptor, ${modules.length}> kFeatures{{
${rows}
}};
}  // namespace

const FeatureDescriptor *feature_registry_data() noexcept {
  return kFeatures.data();
}

std::size_t feature_registry_size() noexcept {
  return kFeatures.size();
}

}  // namespace supernote::generated
`;
}

function installerDeclaration(symbol) {
  return `extern "C" void ${symbol}(
    void *runtime, void *feature_registry, const void *feature_session);`;
}

function renderPluginBindings(modules) {
  const declarations = [];
  const registrations = [];
  for (const module of modules) {
    declarations.push(installerDeclaration(module.installers.native.symbol));
    if (module.installers.jvm !== null) {
      declarations.push(installerDeclaration(module.installers.jvm.symbol));
    }
    const calls = [
      `    ${module.installers.native.symbol}(&runtime, &features, &feature_session);`,
    ];
    if (module.installers.jvm !== null) {
      calls.push(
        `    ${module.installers.jvm.symbol}(&runtime, &features, &feature_session);`,
      );
    }
    registrations.push(`  {
    auto feature_session = supernote::runtime::FeatureSession::create(
        runtime_session, supernote::runtime::process_services().cleanup());
${calls.join('\n')}
  }`);
  }
  return `// Generated by @supernote/runtime. Do not edit.
#include <jsi/jsi.h>

#include "runtime_services.hpp"

#include <cstddef>
#include <memory>
#include <string>
#include <utility>

${declarations.join('\n\n')}

namespace supernote::generated {
namespace {

constexpr char kFeatureRegistryGlobal[] =
    "__supernoteModuleFeatureRegistry_63f6999c8c67";

[[noreturn]] void throw_type_error(
    facebook::jsi::Runtime &runtime, const std::string &message) {
  auto constructor =
      runtime.global().getPropertyAsFunction(runtime, "TypeError");
  throw facebook::jsi::JSError(
      runtime, constructor.callAsConstructor(runtime, message));
}

}  // namespace

void install_plugin_bindings(
    facebook::jsi::Runtime &runtime,
    const std::shared_ptr<supernote::runtime::RuntimeSession> &runtime_session) {
  using facebook::jsi::Function;
  using facebook::jsi::Object;
  using facebook::jsi::PropNameID;
  using facebook::jsi::Value;

  Object features(runtime);
${registrations.join('\n')}
  runtime.global().setProperty(
      runtime, kFeatureRegistryGlobal, std::move(features));

  Object public_runtime(runtime);
  auto feature = Function::createFromHostFunction(
      runtime,
      PropNameID::forAscii(runtime, "feature"),
      1,
      [](facebook::jsi::Runtime &runtime,
         const Value &,
         const Value *arguments,
         std::size_t argument_count) -> Value {
        if (argument_count != 1 || !arguments[0].isString()) {
          throw_type_error(
              runtime,
              "Supernote generated runtime feature(id) expects exactly one string");
        }
        const auto feature_id = arguments[0].asString(runtime).utf8(runtime);
        auto registry = runtime.global().getPropertyAsObject(
            runtime, kFeatureRegistryGlobal);
        auto binding = registry.getProperty(runtime, feature_id.c_str());
        if (binding.isUndefined()) {
          throw_type_error(
              runtime, "unknown Supernote generated feature: " + feature_id);
        }
        return binding;
      });
  public_runtime.setProperty(runtime, "feature", std::move(feature));
  runtime.global().setProperty(
      runtime, "__supernoteModule", std::move(public_runtime));
}

}  // namespace supernote::generated
`;
}

function compose(consumerRoot, outputRoot) {
  const consumer = fs.realpathSync.native(consumerRoot);
  const output = path.resolve(outputRoot);
  const inventory = discover(consumer);
  if (inventory.runtime === null) {
    const error = new Error(
      'Supernote runtime composition [SNMG_RUNTIME_MISSING]: @supernote/runtime is not a declared direct dependency',
    );
    error.code = 'SNMG_RUNTIME_MISSING';
    throw error;
  }
  atomicWrite(
    path.join(output, 'feature_registry.cpp'),
    renderFeatureRegistry(inventory.modules),
  );
  atomicWrite(
    path.join(output, 'plugin_bindings.cpp'),
    renderPluginBindings(inventory.modules),
  );
  atomicWrite(
    path.join(output, 'inventory.json'),
    `${JSON.stringify(inventory, null, 2)}\n`,
  );
  return {
    compositionRoot: output,
    featureIds: inventory.modules.map(module => module.featureId),
    inventory: path.join(output, 'inventory.json'),
    moduleCount: inventory.modules.length,
  };
}

if (require.main === module) {
  if (process.argv.length !== 4) {
    process.stderr.write('usage: node compose-packages.js <consumer-root> <output-root>\n');
    process.exit(2);
  }
  try {
    process.stdout.write(`${JSON.stringify(compose(process.argv[2], process.argv[3]))}\n`);
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exit(1);
  }
}

module.exports = {compose, renderFeatureRegistry, renderPluginBindings};
